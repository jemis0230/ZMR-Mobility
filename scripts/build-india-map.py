"""Builds src/lib/indiaMapData.ts — simplified SVG paths for India's states/UTs.

Source: "India States (Admin2)" from the DataMeet maps repository
  https://github.com/datameet/maps/tree/master/States  (files Admin2.shp/.dbf/.shx/.prj)
  by the DataMeet India community, licensed CC BY 4.0
  (https://creativecommons.org/licenses/by/4.0/). The rendered map carries this attribution.

Usage: python3 scripts/build-india-map.py <dir containing Admin2.shp> > src/lib/indiaMapData.ts
Requires: pip install pyshp shapely
"""
import math, sys
import shapefile
from shapely.geometry import shape

SRC = sys.argv[1]
WIDTH, PAD = 600, 8
LAT0 = 22.0                      # standard parallel for the equirectangular projection
TOLERANCE = 0.045                # degrees (~1 px at this size)
MIN_AREA = 0.0008                # drop specks smaller than this (deg²)

r = shapefile.Reader(f"{SRC}/Admin2")
minx, miny, maxx, maxy = r.bbox
kx = math.cos(math.radians(LAT0))
scale = (WIDTH - 2 * PAD) / ((maxx - minx) * kx)
height = round((maxy - miny) * scale + 2 * PAD)

def px(lon, lat):
    return ((lon - minx) * kx * scale + PAD, (maxy - lat) * scale + PAD)

def ring_d(coords):
    pts = [px(x, y) for x, y in coords]
    out = [f"M{pts[0][0]:.1f} {pts[0][1]:.1f}"]
    prev = pts[0]
    for x, y in pts[1:]:
        if abs(x - prev[0]) < 0.05 and abs(y - prev[1]) < 0.05:
            continue
        out.append(f"L{x:.1f} {y:.1f}")
        prev = (x, y)
    return "".join(out) + "Z"

states = []
for sr in r.iterShapeRecords():
    name = sr.record[0]
    geom = shape(sr.shape.__geo_interface__).buffer(0).simplify(TOLERANCE, preserve_topology=True)
    polys = [geom] if geom.geom_type == "Polygon" else list(geom.geoms)
    parts = []
    for p in polys:
        if p.area < MIN_AREA and name not in ("Lakshadweep", "Chandigarh", "Puducherry", "Delhi"):
            continue
        parts.append(ring_d(p.exterior.coords))
    states.append((name, "".join(parts)))

states.sort(key=lambda s: s[0])
print("// Generated by scripts/build-india-map.py — do not edit by hand.")
print("// India states/UTs (simplified) from DataMeet India community, CC BY 4.0:")
print("// https://github.com/datameet/maps/tree/master/States")
print(f"export const INDIA_MAP_VIEWBOX = {{ width: {WIDTH}, height: {height} }} as const;")
print(f"export const INDIA_MAP_PROJECTION = {{ minLon: {minx!r}, maxLat: {maxy!r}, kx: {kx!r}, scale: {scale!r}, pad: {PAD} }} as const;")
print("export const INDIA_STATE_PATHS: { name: string; d: string }[] = [")
for name, d in states:
    print(f'  {{ name: "{name}", d: "{d}" }},')
print("];")
